-- ---------------------------------------------------------------------
-- Foreign keys.
--
-- Added separately, and only when absent, so that databases where
-- ddl-auto=update silently skipped them end up with the same constraints
-- as a database created from scratch.
-- ---------------------------------------------------------------------

do $$
declare
    fk record;
begin
    for fk in
        select *
          from (values
                ('form16',                     'fk_form16_employee',
                 'employee_id',                'employees'),
                ('form16_challan',             'fk_form16_challan_form16',
                 'form16_id',                  'form16'),
                ('form16_chapter_via',         'fk_form16_chapter_via_form16',
                 'form16_id',                  'form16'),
                ('form16_exemption',           'fk_form16_exemption_form16',
                 'form16_id',                  'form16'),
                ('form16_last_fields',         'fk_form16_last_fields_form16',
                 'form16_id',                  'form16'),
                ('form16_quarter',             'fk_form16_quarter_form16',
                 'form16_id',                  'form16'),
                ('form16_salary',              'fk_form16_salary_form16',
                 'form16_id',                  'form16'),
                ('form16_section16_deduction', 'fk_form16_section16_deduction_form16',
                 'form16_id',                  'form16'),
                ('form16_verification',        'fk_form16_verification_form16',
                 'form16_id',                  'form16')
               ) as t(table_name, constraint_name, column_name, referenced_table)
    loop
        if not exists (
            select 1
              from pg_constraint
             where conname = fk.constraint_name
               and conrelid = to_regclass(fk.table_name)
        ) then
            execute format(
                'alter table %I add constraint %I foreign key (%I) references %I',
                fk.table_name, fk.constraint_name, fk.column_name, fk.referenced_table
            );
        end if;
    end loop;
end $$;
