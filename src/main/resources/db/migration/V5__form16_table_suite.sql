    active boolean not null,
    employment_from date,
    employment_to date,
    last_updated_on date not null,
    opting_out_115bac_1a boolean,
    certificate_no varchar(8) not null unique,
    employee_id bigint not null,
    id bigint generated by default as identity,
    assessment_year varchar(20) not null,
    deductor_pan varchar(20),
    deductor_tan varchar(20),
    employee_pan varchar(20),
    employer_phone varchar(20),
    employer_email varchar(150),
    employer_name varchar(200),
    cit_tds_address varchar(2000),
    employee_address varchar(2000),
    employer_address varchar(2000),
    primary key (id),
    constraint uk_form16_employee_assessment_year unique (employee_id, assessment_year)
);


