-- =====================================================================
-- V5 - Form 16 table suite
-- =====================================================================
-- The form_16 and Form_16A modules (10 entities) shipped without any
-- migration. They were only ever created in development by
-- spring.jpa.hibernate.ddl-auto=update, so V1 never contained them.
--
-- On a brand-new database that means Flyway finishes at V4 and Hibernate
-- then aborts startup with:
--
--     SchemaManagementException: Schema validation: missing table [form16]
--
-- because every profile runs ddl-auto=validate. DigitalOcean Managed
-- PostgreSQL starts empty, so this migration is what makes a first
-- production boot possible.
--
-- Column definitions are exactly what Hibernate 7.2 generates for these
-- entities (captured from the schema-generation script), so the tables
-- validate cleanly.
--
-- Every statement is idempotent: databases that already created these
-- tables through ddl-auto=update are skipped rather than failing, and
-- foreign keys are added only when missing - ddl-auto=update logs
-- constraint failures as warnings, so they may not have been created.
--
-- Never edit an applied migration. Add V6, V7, ... for further changes.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Parent table: one certificate per employee per assessment year.
-- Child tables are created after it because they reference it.
-- ---------------------------------------------------------------------

